class TestShippedConfigs:
    """Guards the configs against flag renames and typos."""

    @pytest.mark.parametrize("relative, parse, extra", SHIPPED_CONFIGS)
    def test_parses(self, relative, parse, extra):
        path = REPO_ROOT / relative
        assert path.is_file(), f"missing shipped config {relative}"
        parse(["--config", str(path)] + extra)

    def test_every_config_file_is_covered(self):
        """A new config must be added to SHIPPED_CONFIGS, not left untested."""
        on_disk = {
            p.relative_to(REPO_ROOT).as_posix()
            for p in CONFIG_DIR.rglob("*")
            if p.suffix in (".yaml", ".yml", ".json", ".jsonc")
        }
        assert on_disk == {relative for relative, _, _ in SHIPPED_CONFIGS}

    def test_gemma_game_modes_share_inputs_but_not_outputs(self):
        """Each elicitation mode must resume into its own result file."""
        root = REPO_ROOT / "configs/games"
        names = [
            "HHH_new_paper_bothAI_anthropic_batch_20260826_01_eval-mcq_focal-gemma-4-31B-it.yaml",
            "HHH_new_paper_bothAI_anthropic_batch_20260826_01_eval-open_focal-gemma-4-31B-it_user-judge-gpt-5.6-luna.yaml",
            "HHH_new_paper_bothAI_anthropic_batch_20260826_01_eval-play_focal-gemma-4-31B-it_fallback-judge-gpt-5.6-luna.yaml",
        ]
        parsed = [
            evaluate_games.parse_args(["--config", str(root / name)])
            for name in names
        ]
        assert {args.mode for args in parsed} == {"mcq", "open", "play"}
        assert len({args.output_name for args in parsed}) == 3
        assert len({args.scenarios_dir for args in parsed}) == 1
        assert len({args.model for args in parsed}) == 1
        assert all(args.max_tokens == 4096 for args in parsed)

    def test_the_two_evaluate_modes_write_to_different_files(self):
        """Shared output names would make the second run resume into nothing."""
        mcq = evaluate_models.parse_args([
            "--config",
            str(REPO_ROOT / "configs/solo/HHH_new_solo_20260826_01_eval-mcq_focal-gemma-4-31B-it.yaml"),
        ])
        interactive = evaluate_models.parse_args([
            "--config",
            str(REPO_ROOT
                / "configs/solo/HHH_new_solo_20260826_01_eval-interactive_focal-gemma-4-31B-it_user-judge-gpt-5.6-luna.yaml"),
        ])
        assert mcq.interactive is False and interactive.interactive is True
        assert mcq.output_dir == interactive.output_dir
        assert mcq.output_name != interactive.output_name
        assert None not in (mcq.output_name, interactive.output_name)

    def test_the_stages_agree_on_value_set_and_paths(self):
        """The four stages have to describe one run, not four."""
        root = REPO_ROOT / "configs/solo"
        generate = generate_scenarios.parse_args([
            "--config", str(root / "HHH_new_solo_20260826_01_generate_generator-claude-sonnet-5.yaml"),
            "-v1", "harmlessness", "-v2", "honesty",
        ])
        filtered = filter_scenarios.parse_args([
            "--config", str(root / "HHH_new_solo_20260826_01_filter_judge-gpt-5.6-luna.yaml"),
            "-i", "unused.json",
        ])
        mcq = evaluate_models.parse_args([
            "--config", str(root / "HHH_new_solo_20260826_01_eval-mcq_focal-gemma-4-31B-it.yaml"),
        ])
        analyze = analyze_experiment.parse_args([
            "--config", str(root / "HHH_new_solo_20260826_01_analyze.yaml"),
        ])

        assert generate.value_set == filtered.value_set == analyze.value_set

        # Generation writes under the directory filtering reads its input from,
        # filtering writes the CSV evaluation globs, and analysis reads both.
        assert generate.output_dir.startswith(filtered.output_dir + "/")
        assert mcq.scenarios_dir == filtered.output_dir
        assert analyze.scenario_dir == filtered.output_dir
        assert analyze.model_dir == mcq.output_dir

        # The judge that admits scenarios is also the judge that reads the
        # conversations, and neither is the generator.
        interactive = evaluate_models.parse_args([
            "--config",
            str(root / "HHH_new_solo_20260826_01_eval-interactive_focal-gemma-4-31B-it_user-judge-gpt-5.6-luna.yaml"),
        ])
        assert (
            interactive.judge_model
            .removeprefix("openai:openai.")
            .removeprefix("paid-openai:")
        ) == filtered.model
        assert filtered.model != generate.model
        assert mcq.model != generate.model
